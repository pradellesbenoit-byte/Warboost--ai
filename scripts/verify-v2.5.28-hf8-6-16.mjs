// Dynamic auth contract: a successful password call returns the same session and emits SIGNED_IN.
const storageMap=new Map();
const storage={getItem:k=>storageMap.get(k)||null,setItem:(k,v)=>storageMap.set(k,v),removeItem:k=>storageMap.delete(k)};
const payload={access_token:'token-abc',refresh_token:'refresh-abc',expires_in:3600,token_type:'bearer',user:{id:'player-123',email:'player@example.com'}};
const fakeFetch=async()=>({ok:true,status:200,async json(){return payload}});
const client=createWarBoostSupabaseAuthClient({url:'https://project.supabase.co',key:'publishable',storage,fetchImpl:fakeFetch,requestTimeoutMs:3000});
let event=null,eventSession=null;
client.auth.onAuthStateChange((e,s)=>{event=e;eventSession=s});
const result=await client.auth.signInWithPassword({email:'PLAYER@example.com',password:'secret'});
assert.equal(result.error,null);
assert.equal(result.data.session.user.id,'player-123');
assert.equal(result.data.session.access_token,'token-abc');
assert.equal(event,'SIGNED_IN');
assert.equal(eventSession.user.id,'player-123');
const stored=await client.auth.getSession();
assert.equal(stored.data.session.user.id,'player-123');
assert.equal(stored.data.session.access_token,'token-abc');
