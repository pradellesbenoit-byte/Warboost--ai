import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {previewAllianceRankChanges,applyAllianceRankChanges,rankManagementKey} from '../lib/alliance-rank-management.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const mk=(name,role,power=100)=>({name,role,power_m:power,hq_level:35,server_id:'884',alliance_tag:'ALL4',membership_history:[],updated_at:'2026-09-12T08:00:00.000Z'});
const members=[mk('Nono 50','R5',275.7)];
for(let i=1;i<=10;i++)members.push(mk(`R4-${i}`,'R4',300-i));
for(let i=1;i<=69;i++)members.push(mk(`R3-${i}`,'R3',250-i));
for(let i=1;i<=11;i++)members.push(mk(`R2-${i}`,'R2',180-i));
for(let i=1;i<=2;i++)members.push(mk(`R1-${i}`,'R1',100-i));
const key=rankManagementKey(members.find(x=>x.name==='R4-1'));
const preview=previewAllianceRankChanges(members,[{key,to_role:'R3'}],{maxR4:10});
assert.equal(preview.ok,true);assert.equal(preview.before.R4,10);assert.equal(preview.after.R4,9);assert.equal(preview.after.R3,70);
const applied=applyAllianceRankChanges(members,[{key,to_role:'R3'}],{now:'2026-09-12T11:20:00.000Z',maxR4:10});
assert.equal(applied.members.find(x=>x.name==='R4-1').role,'R3');
assert.ok(applied.members.find(x=>x.name==='R4-1').membership_history.some(x=>x.type==='role_changed'&&x.from_role==='R4'&&x.to_role==='R3'));
const app=read('app.js'),api=read('api/alliance-role.js'),health=read('api/health.js'),sw=read('sw.js'),pkg=JSON.parse(read('package.json'));
assert.match(app,/RELEASE_LABEL="HF8\.6\.4"/);
assert.match(app,/persistCanonicalRosterRankBatch/);
assert.match(app,/await persistCanonicalRosterRankBatch\(preview\)/);
assert.match(app,/render\(\);rankManagerStatus\("rank_manager_saved"/);
assert.match(app,/await syncAll\(\)\.catch/);
assert.match(api,/roster_rank_changes/);
assert.match(api,/updateAllianceScopeRoster/);
assert.match(api,/member_identity_ambiguous/);
assert.match(api,/r4_limit/);
assert.match(api,/r5_protected/);
assert.match(health,/alliance_rank_manager_immediate_render:true/);
assert.match(health,/alliance_rank_manager_canonical_batch_persistence:true/);
assert.match(health,/alliance_rank_manager_cloud_refresh_no_revert:true/);
assert.match(sw,/hf8-6-4-rank-persistence/);
assert.match(pkg.description,/HF8\.6\.4/);
const migrations=fs.readdirSync(path.join(root,'supabase')).filter(x=>/hf8[_-]?6[_-]?4/i.test(x));assert.equal(migrations.length,0,'HF8.6.4 must not add a Supabase migration');
console.log('WarBoost V2.5.28 HF8.6.4 Rank Persistence Reliability verification: PASS');
